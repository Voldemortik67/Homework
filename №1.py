names = ["Анна", "Иван", "Мария", "Олег"]  # я создаю список участников кружка
name = input("Введите имя: ")  # я прошу пользователя ввести имя и сохраняю его в переменную name

if name in names:  # я проверяю оператором in, есть ли введённое имя в списке
    print("Участник найден")  # если имя есть, я вывожу это сообщение
else:  # если имени в списке нет, то выполнится блок ниже
    print("Участник не найден")  # в этом случае я вывожу другое сообщение