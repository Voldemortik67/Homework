numbers = [12, 4, 9, 1, 6, 3]  # это мой исходный список
def merge_sort(lst):  # я создаю функцию, которая будет сортировать список
    if len(lst) <= 1:  # если в списке 0 или 1 элемент, он уже отсортирован
        return lst  # поэтому я просто возвращаю его (это условие остановки рекурсии)

    middle = len(lst) // 2  # я нахожу середину списка
    left = merge_sort(lst[:middle])  # я рекурсивно сортирую левую половину
    right = merge_sort(lst[middle:])  # и так же сортирую правую половину

    result = []  # сюда я буду собирать объединённый отсортированный список
    i = 0  # индекс, по которому я иду по левой части
    j = 0  # индекс, по которому я иду по правой части

    while i < len(left) and j < len(right):  # пока в обеих частях ещё есть элементы
        if left[i] <= right[j]:  # я сравниваю текущие элементы двух частей
            result.append(left[i])  # если левый меньше или равен, то беру его
            i = i + 1  # и двигаюсь дальше по левой части
        else:  # иначе меньше элемент из правой части
            result.append(right[j])  # я беру его
            j = j + 1  # и двигаюсь дальше по правой части

    while i < len(left):  # если в левой части что-то осталось
        result.append(left[i])  # я добавляю остаток в конец результата
        i = i + 1  # и перехожу к следующему элементу

    while j < len(right):  # если в правой части что-то осталось
        result.append(right[j])  # я добавляю остаток в конец результата
        j = j + 1  # и перехожу к следующему элементу

    return result  # я возвращаю собранный отсортированный список


print("Исходный список:", numbers)  # я вывожу его до сортировки
sorted_numbers = merge_sort(numbers)  # я вызываю свою функцию и сохраняю результат
print("Отсортированный список:", sorted_numbers)  # я вывожу получившийся отсортированный список