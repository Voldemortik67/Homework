numbers = [29, 10, 14, 37, 13]  # это мой исходный список, который я буду сортировать
print("Исходный список:", numbers)  # я вывожу список до сортировки

for i in range(len(numbers) - 1):  # каждый проход этого цикла ставит на место один элемент
    min_index = i  # сначала я считаю минимальным элемент с индексом i
    for j in range(i + 1, len(numbers)):  # я просматриваю все элементы правее него
        if numbers[j] < numbers[min_index]:  # если нашёл элемент меньше текущего минимального
            min_index = j  # я запоминаю его индекс как новый минимум

    temp = numbers[i]  # я кладу элемент с позиции i во временную переменную
    numbers[i] = numbers[min_index]  # на позицию i ставлю найденный минимум
    numbers[min_index] = temp  # а старый элемент отправляю на место минимума (так я поменял их местами)

    print("Проход", i + 1, ":", numbers)  # после каждого прохода я вывожу текущее состояние списка

print("Результат:", numbers)  # в конце я вывожу уже отсортированный список