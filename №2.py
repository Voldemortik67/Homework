numbers = [2, 5, 8, 11, 14, 18, 21, 25, 30]  # у меня есть отсортированный список (для бинарного поиска это обязательно)
target = 18  # я записываю число, которое нужно найти

left = 0  # левая граница поиска, я начинаю с первого элемента
right = len(numbers) - 1  # правая граница, это индекс последнего элемента
result = -1  # сначала я считаю, что числа нет, поэтому в результате -1

while left <= right:  # я повторяю поиск, пока левая граница не зашла за правую
    middle = (left + right) // 2  # я нахожу индекс середины текущего куска списка
    if numbers[middle] == target:  # если число в середине равно искомому
        result = middle  # я запоминаю его индекс
        break  # и выхожу из цикла, потому что число уже найдено
    elif numbers[middle] < target:  # если число в середине меньше искомого
        left = middle + 1  # то искомое справа, и я сдвигаю левую границу
    else:  # иначе число в середине больше искомого
        right = middle - 1  # значит искать надо слева, и я сдвигаю правую границу

print(result)  # я вывожу индекс найденного числа (или -1, если его нет)